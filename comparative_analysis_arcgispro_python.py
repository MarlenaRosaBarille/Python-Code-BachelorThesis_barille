"""## 12. Hotspot analysis (Section 4.4)

Hotspots are defined as cells exceeding 20 t ha⁻¹ yr⁻¹ (threshold from Meshesha et al. 2012; FAO & ITPS 2015 classifies anything >20 as high on tropical cropland).

Three steps here:

1. Binary hotspot raster per method (1 = hotspot, 0 = non-hotspot)
2. Combination raster using binary encoding so every pixel carries which method(s) flagged it
3. Jaccard similarity index between F1 and F2 hotspot layers
"""

HOT_THRESH = 20
OUTPUT_DIR = r"S:\group\ess_demand4restoration\bachelorThesisMarlena\outputshot"
os.makedirs(OUTPUT_DIR, exist_ok=True)

arcpy.env.workspace = r"S:\group\ess_demand4restoration\bachelorThesisMarlena"
arcpy.env.overwriteOutput = True

NAME_BL = "blloss_clip"
NAME_V1 = "F1loss_clip"
NAME_V2 = "F2los_clip"

print("Creating binary hotspot rasters...")

r_bl = Raster(NAME_BL)
r_v1 = Raster(NAME_V1)
r_v2 = Raster(NAME_V2)

hot_bl = Con(r_bl >= HOT_THRESH, 1, 0)
hot_v1 = Con(r_v1 >= HOT_THRESH, 1, 0)
hot_v2 = Con(r_v2 >= HOT_THRESH, 1, 0)

path_hot_bl = os.path.join(OUTPUT_DIR, "Hotspot_Baseline.tif")
path_hot_v1 = os.path.join(OUTPUT_DIR, "Hotspot_V1_McCool.tif")
path_hot_v2 = os.path.join(OUTPUT_DIR, "Hotspot_V2_Nearing.tif")

hot_bl.save(path_hot_bl); print("  Saved: Hotspot_Baseline.tif")
hot_v1.save(path_hot_v1); print("  Saved: Hotspot_V1_McCool.tif")
hot_v2.save(path_hot_v2); print("  Saved: Hotspot_V2_Nearing.tif")

"""### Combination raster

Binary encoding so every unique combination of method-agreements gets a unique pixel value. Useful for the consensus / partial agreement map (Figure 11 in the appendix).

```
0 = none
1 = V2 only      (Nearing unique — steep slope signal)
2 = V1 only      (McCool unique)
3 = V1 + V2      (both D&G agree, Moore misses)
4 = Baseline only
5 = Baseline + V2
6 = Baseline + V1
7 = all agree    (full consensus)
```
"""

print("Creating combination map...")

hot_bl = Raster(path_hot_bl)
hot_v1 = Raster(path_hot_v1)
hot_v2 = Raster(path_hot_v2)

combo = (hot_bl * 4) + (hot_v1 * 2) + (hot_v2 * 1)

path_combo = os.path.join(OUTPUT_DIR, "Hotspot_Combination.tif")
combo.save(path_combo)
print("Saved:", path_combo)

"""### Jaccard similarity (F1 vs F2)

Jaccard = |F1 ∩ F2| / |F1 ∪ F2|. Quantifies how much the two variant hotspot layers overlap. The thesis reports 91.7% agreement, with 6.7% of cells flagged only by F2 (steep-slope detections that F1 misses).
"""

print("Calculating Jaccard similarity...")

hot_v1 = Raster(path_hot_v1)
hot_v2 = Raster(path_hot_v2)

# Intersection: both V1 and V2 are hotspot
intersection = Con((hot_v1 == 1) & (hot_v2 == 1), 1, 0)
# Union: either V1 or V2 is hotspot
union_r = Con((hot_v1 == 1) | (hot_v2 == 1), 1, 0)
# Cells V2 flags but V1 misses
missed_r = Con((hot_v2 == 1) & (hot_v1 == 0), 1, 0)

# Mean of a binary raster = fraction of 1s
inter_mean  = float(arcpy.GetRasterProperties_management(intersection, "MEAN").getOutput(0))
union_mean  = float(arcpy.GetRasterProperties_management(union_r,      "MEAN").getOutput(0))
v2_mean     = float(arcpy.GetRasterProperties_management(hot_v2,       "MEAN").getOutput(0))
missed_mean = float(arcpy.GetRasterProperties_management(missed_r,     "MEAN").getOutput(0))

jaccard    = inter_mean / union_mean if union_mean > 0 else 0
missed_pct = (missed_mean / v2_mean) * 100 if v2_mean > 0 else 0

# Hotspot coverage per formulation
pct_bl = float(arcpy.GetRasterProperties_management(Raster(path_hot_bl), "MEAN").getOutput(0)) * 100
pct_v1 = float(arcpy.GetRasterProperties_management(hot_v1, "MEAN").getOutput(0)) * 100
pct_v2 = v2_mean * 100

print("\n" + "=" * 50)
print("JACCARD RESULTS")
print("=" * 50)
print(f"\nHotspot coverage (>{HOT_THRESH} t/ha/yr):")
print(f"  Baseline (Moore):  {pct_bl:.1f}%")
print(f"  V1 (McCool):       {pct_v1:.1f}%")
print(f"  V2 (Nearing):      {pct_v2:.1f}%")
print(f"\nJaccard V1 vs V2:              {jaccard:.4f}")
print(f"V2 hotspots missed by V1:      {missed_pct:.1f}%")

# Save the missed-by-F1 raster (for the appendix map showing what F1 misses)
path_missed = os.path.join(OUTPUT_DIR, "Hotspot_MissedByMcCool.tif")
missed_r.save(path_missed)

# Save numerical results to text
with open(os.path.join(OUTPUT_DIR, "jaccard_results.txt"), "w") as f:
    f.write("JACCARD SIMILARITY\n")
    f.write(f"Threshold: >{HOT_THRESH} t/ha/yr\n\n")
    f.write(f"Baseline hotspot %:   {pct_bl:.2f}%\n")
    f.write(f"V1 McCool hotspot %:  {pct_v1:.2f}%\n")
    f.write(f"V2 Nearing hotspot %: {pct_v2:.2f}%\n\n")
    f.write(f"Jaccard V1 vs V2:     {jaccard:.4f}\n")
    f.write(f"V2 missed by V1:      {missed_pct:.1f}%\n")
print("Saved: jaccard_results.txt")

