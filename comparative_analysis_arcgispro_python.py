"""## 9. Kolmogorov–Smirnov tests

Two-sample KS tests for the three pairwise comparisons. Done both globally (on a 500k random subsample of the whole dataframe) and per slope class.

Given the very large sample sizes the p-values are essentially zero everywhere, so the D statistic is theeffect size that matters
"""

# Subsample because ks_2samp gets slow on >25 million points
df_test = df.sample(500_000, random_state=42)

# Global KS tests (whole study area)
print("=" * 50)
print("Global KS tests")
print("=" * 50)

for name, a, b in [
    ("baseline vs v1", df_test["ls_baseline"], df_test["ls_v1"]),
    ("baseline vs v2", df_test["ls_baseline"], df_test["ls_v2"]),
    ("v1 vs v2",       df_test["ls_v1"],       df_test["ls_v2"]),
]:
    res = stats.ks_2samp(a, b, alternative="two-sided", method="auto")
    print(f"{name:<20}  D = {res.statistic:.4f}   p = {res.pvalue:.3e}")

# Per slope class
classes = ["<9%", "9–22%", "22–55%", ">55%"]
ks_results = []

for sc in classes:
    sub = df_test[df_test["slope_class"] == sc]

    comparisons = [
        ("baseline_vs_v1", sub["ls_baseline"], sub["ls_v1"]),
        ("baseline_vs_v2", sub["ls_baseline"], sub["ls_v2"]),
        ("v1_vs_v2",       sub["ls_v1"],       sub["ls_v2"]),
    ]

    for comp_name, a, b in comparisons:
        res = stats.ks_2samp(a, b, alternative="two-sided", method="auto")
        ks_results.append({
            "slope_class": sc,
            "comparison":  comp_name,
            "n":           len(sub),
            "D":           res.statistic,
            "p_value":     res.pvalue,
        })

ks_df = pd.DataFrame(ks_results)
print(ks_df.to_string(index=False))

