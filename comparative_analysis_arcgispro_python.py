method_colors = ["black", "#1D5FA2", "#A03032"]
method_styles = ["-", "--", ":"]

classes = ["<9%", "9–22%", "22–55%", ">55%"]

# x-axis upper limit per slope class (chosen so the curves are readable)
xlims = {"<9%": 5, "9–22%": 25, "22–55%": 60, ">55%": 150}

# stratified random sample per class
sample_size_per_class = 300_000
rng = np.random.default_rng(42)

