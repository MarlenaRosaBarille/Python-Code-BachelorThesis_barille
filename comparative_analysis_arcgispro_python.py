input_rasters = [r_raster, k_raster, ls_raster, c_raster, ru_raster]
labels        = ["R", "K", "LS", "C", "soil_loss"]

pbc_inputs = PixelBlockCollection(
    input_rasters,
    pixel_block_size=(512, 512),
    overlay_type="INTERSECTION",
    nodata_to_values=np.nan,
)

print("Number of blocks (y, x):", pbc_inputs.size)

# Loop through blocks, sample randomly from each one so the final dataframe stays small
sample_per_block = 200  # ~200 random cells per block
input_df_list = []

ny, nx = pbc_inputs.size
rng = np.random.default_rng(42)

for by in range(ny):
    for bx in range(nx):
        block = pbc_inputs[by, bx]
        arrs = [np.squeeze(b.getData()).astype("float64") for b in block]

        valid = np.ones_like(arrs[0], dtype=bool)
        for arr in arrs:
            valid &= ~np.isnan(arr)

        if valid.sum() == 0:
            continue

        # pick a small random subset to keep memory under control
        n_take = min(sample_per_block, int(valid.sum()))
        idx = rng.choice(int(valid.sum()), size=n_take, replace=False)

        block_data = {
            lab: arr[valid].ravel()[idx]
            for lab, arr in zip(labels, arrs)
        }
        input_df_list.append(pd.DataFrame(block_data))

input_df = pd.concat(input_df_list, ignore_index=True)

# Trim to exactly 200'000 if larger
if len(input_df) > 200_000:
    input_df = input_df.sample(200_000, random_state=42).reset_index(drop=True)

print("Input factor sample shape:", input_df.shape)
print(input_df.head())

#Spearman rank correlation: each input factor against soil loss
print("=" * 60)
print("Spearman rank correlation with modelled soil loss")
print("=" * 60)

corr_results = []
for fac in ["R", "K", "LS", "C"]:
    rho, p = stats.spearmanr(input_df[fac], input_df["soil_loss"])
    corr_results.append({"factor": fac, "spearman_rho": rho, "p_value": p})

corr_df = pd.DataFrame(corr_results)
print(corr_df.to_string(index=False))

# coefficientof variation(CV = std / mean * 100) per input factor
print("=" * 60)
print("Coefficient of variation per input factor (whole study area)")
print("=" * 60)

cv_results = []
for path, label in [
    (r_path,  "R"),
    (k_path,  "K"),
    (ls_baseline_path, "LS"),
    (c_path,  "C"),
]:
    mean_val = float(arcpy.GetRasterProperties_management(path, "MEAN").getOutput(0))
    std_val  = float(arcpy.GetRasterProperties_management(path, "STD").getOutput(0))
    cv = (std_val / mean_val) * 100 if mean_val != 0 else np.nan
    cv_results.append({"factor": label, "mean": mean_val, "std": std_val, "CV_pct": cv})

cv_df = pd.DataFrame(cv_results)
print(cv_df.to_string(index=False))

#final Table 2 combining the two
table2 = corr_df.merge(cv_df[["factor", "CV_pct"]], on="factor")
