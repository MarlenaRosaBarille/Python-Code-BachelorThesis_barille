for ax, sc in zip(axes.flat, classes):
    sub = df[df["slope_class"] == sc]
    n_class = len(sub)
    if n_class > sample_size_per_class:
        sub = sub.sample(sample_size_per_class, random_state=42)
    n = len(sub)

    for method, label, color, style in zip(methods, method_labels, method_colors, method_styles):
        vals = np.sort(sub[method].dropna().to_numpy())
        cdf = np.arange(1, len(vals) + 1) / len(vals)
        ax.plot(vals, cdf, color=color, linestyle=style, linewidth=1.2, label=label)

    # KS D values for the legend (computed on the same subsample)
