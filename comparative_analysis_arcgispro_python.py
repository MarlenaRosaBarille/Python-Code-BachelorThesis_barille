"""## 4. Slope stratification

The slope raster comes out of ArcGIS in degrees. For the analysis i need it in % because that's what the slope class thresholds in the literature (9%, 22%, 55%) are defined in. The conversion is `slope_pct = tan(slope_deg) * 100`.

The four slope classes come straight from the math of the slope-steepness equations:
- **<9%** — both McCool branches active; the low-slope branch
- **9–22%** — McCool high-slope branch starts, Nearing still fits McCool
- **22–55%** — Nearing diverges from McCool, fitted on Liu et al. (1994) data
- **>55%** — outside the empirical calibration range of any S factor formulation
"""

# Convert slope from degrees to %
